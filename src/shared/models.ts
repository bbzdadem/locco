import type { MediaKind, MediaModel } from './types'
import mediaModels from './media-models.json'

export const CHAT_MODELS = [
  { id: 'claude-sonnet-5-5', label: 'Claude Sonnet 5.5', api: 'claude' },
  { id: 'claude-opus-5-5', label: 'Claude Opus 5.5', api: 'claude' },
  { id: 'claude-haiku-5-5', label: 'Claude Haiku 5.5', api: 'claude' },
  { id: 'gpt-6-sol', label: 'GPT 6 Sol', api: 'responses' },
  { id: 'gemini-3-8-flash-openai', label: 'Gemini 3.8 Flash', api: 'openai' },
] as const
export type ChatModel = (typeof CHAT_MODELS)[number]
export const chatModel = (id?: string): ChatModel => CHAT_MODELS.find((m) => m.id === id) ?? CHAT_MODELS[0]

// Generated by scripts/sync-models.mjs from docs.kie.ai. Hidden if the docs mark them deprecated.
export const MEDIA_MODELS = (mediaModels as MediaModel[]).filter((m) => ![m.text, m.image, m.tool].some((s) => s?.deprecated))
export const generators = (kind: MediaKind) => MEDIA_MODELS.filter((m) => m.kind === kind && (m.text || m.image))
export const kindOf = (modelId: string): MediaKind => MEDIA_MODELS.find((m) => m.id === modelId)?.kind ?? 'image'
