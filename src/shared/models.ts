// Voices come from the user's ElevenLabs account (loaded at start and when the key is saved), so the menu is filled in at runtime.
export const ELEVEN_VOICES: { id: string; name: string; about: string; premade?: boolean }[] = []
export function setElevenVoices(list: { id: string; name: string; about: string; premade?: boolean }[]) {
  ELEVEN_VOICES.splice(0, ELEVEN_VOICES.length, ...list)
  const f = ELEVEN_MODELS[0].text!.fields.find((x) => x.name === 'voice')!
  f.enum = list.map((v) => v.id)
  f.enumLabels = Object.fromEntries(list.map((v) => [v.id, v.name]))
  // Default to a standard ElevenLabs voice, never one of your own (a clone of you shouldn't speak unless you pick it).
  f.default = (list.find((v) => v.premade) ?? list[0])?.id
}

// kie's ElevenLabs is switched off (it failed every time on 8 Nov 2026); locco uses the user's own ElevenLabs key instead.
const OFF = new Set(['tts-turbo', 'tts-multilingual'])

// Generated by scripts/sync-models.mjs from docs.kie.ai. Hidden if the docs mark them deprecated.
export const MEDIA_MODELS = [
  ...(mediaModels as MediaModel[]).filter((m) => ![m.text, m.image, m.tool].some((s) => s?.deprecated)).map((m) => (OFF.has(m.id) ? { ...m, hidden: true } : m)),
  ...ELEVEN_MODELS,
]
export const generators = (kind: MediaKind) => MEDIA_MODELS.filter((m) => m.kind === kind && (m.text || m.image) && !m.hidden)
export const kindOf = (modelId: string): MediaKind => MEDIA_MODELS.find((m) => m.id === modelId)?.kind ?? 'image'

